import { useEffect } from 'react'
import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query'
import { fetchTrends, fetchTrendSnapshot, refreshTrends, TrendsResponse } from '../services/api'

// Deduplicates concurrent snapshot loads: several pages mount useTrends at
// the same time, but the static file only needs to be fetched once.
const snapshotRequests = new Map<string, Promise<TrendsResponse | null>>()

function loadTrendSnapshot(region: string): Promise<TrendsResponse | null> {
    const existing = snapshotRequests.get(region)
    if (existing) return existing

    const request = fetchTrendSnapshot(region)
    snapshotRequests.set(region, request)
    // Free the slot once settled so a later mount can retry after a failure
    request.then(() => snapshotRequests.delete(region))
    return request
}

export function useTrends(region: string) {
    const queryClient = useQueryClient()

    // Seed the query with the static snapshot (generated by
    // scripts/fetch-trending.mjs) so first-time visitors see trending data
    // immediately. The live request has already started at query mount, so
    // seeding never blocks or cancels it — the live response simply replaces
    // the seeded data when it arrives.
    useEffect(() => {
        // Cached data (live response or an earlier seed) is at least as fresh
        // as the snapshot — nothing to do.
        if (queryClient.getQueryData(['trends', region]) !== undefined) return

        let cancelled = false

        loadTrendSnapshot(region).then((snapshot) => {
            if (cancelled || !snapshot) return
            // Re-check: the live response may have arrived while loading.
            if (queryClient.getQueryData(['trends', region]) === undefined) {
                queryClient.setQueryData(['trends', region], snapshot)
            }
        })

        return () => {
            cancelled = true
        }
    }, [queryClient, region])

    return useQuery<TrendsResponse>({
        queryKey: ['trends', region],
        queryFn: () => fetchTrends(region),
        staleTime: 1000 * 60 * 30, // 30 minutes
        gcTime: 1000 * 60 * 60, // Keep in cache for 1 hour
        refetchOnWindowFocus: false,
        retry: 3, // Increased retries for cold start
        retryDelay: (attemptIndex) => Math.min(1000 * 2 ** attemptIndex, 10000), // Exponential backoff: 1s, 2s, 4s
    })
}

export function useRefreshTrends() {
    const queryClient = useQueryClient()

    return useMutation({
        mutationFn: (region: string) => refreshTrends(region),
        onSuccess: (_data, region) => {
            // Invalidate and refetch trends for this region
            queryClient.invalidateQueries({ queryKey: ['trends', region] })
        },
    })
}
